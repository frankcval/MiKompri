using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using MiKompri.ShoppingList.Infrastructure.Persistence;
using System.Linq;

namespace MiKompri.ShoppingList.Application.Tests.IntegrationTest
{
    public class CustomWebApplicationFactory<Program>
     : WebApplicationFactory<Program> where Program : class
    {
        private readonly string _dbName = $"ShoppingListTestDb_{Guid.NewGuid()}";
        private string? _postgresAdmin;

        public FakeUsersApiState UsersApiState { get; } = new();

        protected override void ConfigureWebHost(IWebHostBuilder builder)
        {
            builder.ConfigureServices(services =>
            {
                var descriptors = services
                    .Where(d => d.ServiceType == typeof(DbContextOptions<ShoppingListDbContext>))
                    .ToList();

                foreach (var descriptor in descriptors)
                {
                    services.Remove(descriptor);
                }

                var postgres = Environment.GetEnvironmentVariable("MIKOMPRI_TEST_POSTGRES");
                if (!string.IsNullOrWhiteSpace(postgres))
                {
                    _postgresAdmin = postgres;
                    using var admin = new Npgsql.NpgsqlConnection(postgres);
                    admin.Open();
                    using var create = new Npgsql.NpgsqlCommand($"CREATE DATABASE \"{_dbName}\"", admin);
                    create.ExecuteNonQuery();
                    var connection = new Npgsql.NpgsqlConnectionStringBuilder(postgres) { Database = _dbName }.ConnectionString;
                    services.AddDbContext<ShoppingListDbContext>(options => options.UseNpgsql(connection));
                }
                else
                {
                    var inMemoryServiceProvider = new ServiceCollection().AddEntityFrameworkInMemoryDatabase().BuildServiceProvider();
                    services.AddDbContext<ShoppingListDbContext>(options => { options.UseInMemoryDatabase(_dbName); options.UseInternalServiceProvider(inMemoryServiceProvider); });
                }

                services.AddAuthentication(options =>
                {
                    options.DefaultAuthenticateScheme = TestAuthHandler.SchemeName;
                    options.DefaultChallengeScheme = TestAuthHandler.SchemeName;
                }).AddScheme<AuthenticationSchemeOptions, TestAuthHandler>(TestAuthHandler.SchemeName, _ => { });

                services.AddSingleton(UsersApiState);
                services.AddTransient<FakeUsersApiHandler>();
                services.AddHttpClient("UsersApi")
                    .ConfigurePrimaryHttpMessageHandler(sp => sp.GetRequiredService<FakeUsersApiHandler>());

                builder.UseEnvironment("Development");
            });
        }

        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);
            if (disposing && _postgresAdmin is not null)
            {
                // This database name is generated by this factory, never user input.
                using var admin = new Npgsql.NpgsqlConnection(_postgresAdmin);
                admin.Open();
                using var drop = new Npgsql.NpgsqlCommand($"DROP DATABASE IF EXISTS \"{_dbName}\" WITH (FORCE)", admin);
                drop.ExecuteNonQuery();
                _postgresAdmin = null;
            }
        }
    }
}
