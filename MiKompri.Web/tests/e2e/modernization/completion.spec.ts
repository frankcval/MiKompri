test('@smoke 009 cancelling product loading keeps focus and never reopens the dialog', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await modernFixtures(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/src/features/shopping-lists/components/AddProductsDialogContent.tsx*', async route => {
    await gate
    await route.continue()
  })
  await openHarness(page, `/personal-lists/${ids.personal}`)
  const add = page.getByRole('button', { name: 'Añadir productos', exact: true })
  await add.click()
  const loading = page.getByRole('dialog', { name: 'Preparando productos' })
  await expect(loading).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Marcar comprado: Tomates' })).toHaveCount(0)
  const cancel = loading.getByRole('button', { name: 'Cancelar apertura de productos' })
  await expect.poll(async () => (await cancel.boundingBox())?.height ?? 0).toBeGreaterThanOrEqual(44)
  await cancel.click()
  await expect(add).toBeFocused()
  const response = page.waitForResponse(result => result.url().includes('/AddProductsDialogContent.tsx'))
  release()
  await response
  await page.waitForLoadState('networkidle')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await add.click()
  await expect(page.getByRole('dialog', { name: 'Añadir productos a la lista' }).getByRole('group', { name: 'Seleccionar producto' })).toBeVisible()
})

